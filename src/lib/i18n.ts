const MESSAGES: Record<Lang, Dict> = { en, es, pt: {}, ru: {} };

export function detectLang(): Lang {
  const raw =
    (typeof navigator !== "undefined" && (navigator.language || navigator.languages?.[0])) || "en";
  const code = raw.toLowerCase().slice(0, 2);
  return (LANGS as string[]).includes(code) ? (code as Lang) : "en";
}

export function translator(lang: Lang) {
  return (key: string): string => MESSAGES[lang]?.[key] ?? en[key] ?? key;
}
